"""
Script to synchronize baseline/menu.csv to site/data/menu.csv and site/js/menu-data.js.
Ensures single source of truth for the menu across the cafe project.
"""
import csv
import json
import os
import shutil

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_MENU_CSV = os.path.join(BASE_DIR, "baseline", "menu.csv")
DEST_MENU_CSV = os.path.join(BASE_DIR, "site", "data", "menu.csv")
DEST_MENU_JS = os.path.join(BASE_DIR, "site", "js", "menu-data.js")

def sync_menu():
    if not os.path.exists(SRC_MENU_CSV):
        raise FileNotFoundError(f"Source menu CSV not found at {SRC_MENU_CSV}")

    os.makedirs(os.path.dirname(DEST_MENU_CSV), exist_ok=True)
    os.makedirs(os.path.dirname(DEST_MENU_JS), exist_ok=True)

    # 1. Copy CSV file directly
    shutil.copyfile(SRC_MENU_CSV, DEST_MENU_CSV)
    print(f"Copied {SRC_MENU_CSV} -> {DEST_MENU_CSV}")

    # 2. Parse CSV to structured JSON/JS
    items = []
    with open(SRC_MENU_CSV, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            items.append({
                "id": row["item_id"].strip(),
                "name": row["name"].strip(),
                "category": row["category"].strip(),
                "description": row["description"].strip(),
                "price": float(row["price_usd"].strip()),
                "diet": row["diet"].strip(),
                "containsEgg": row["contains_egg"].strip().lower() == "yes",
                "pairsWith": row["pairs_with"].strip(),
                "foodCost": float(row["food_cost_usd"].strip())
            })

    js_content = f"// Auto-generated by scripts/sync_menu.py from baseline/menu.csv\n" \
                 f"// Single source of truth for KGP Vibes Cafe menu items\n" \
                 f"window.MENU_DATA = {json.dumps(items, indent=2)};\n"

    with open(DEST_MENU_JS, mode="w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"Generated {DEST_MENU_JS} with {len(items)} items.")

if __name__ == "__main__":
    sync_menu()
